// Inline the registry's FILE LISTING into `lib/registry.generated.ts`.
//
// WHY. `lib/registry.ts` walks `components/registry/` with `readdirSync` on
// every call to work out which files exist for each component. That is the last
// directory walk in this app's read path, and Cloudflare Workers has no
// filesystem. (`lib/registry-source.ts` also walks, and additionally reads file
// CONTENT — 3.8 MB across 609 files. That one is a deployment-shape decision,
// not a mechanical swap, and is deliberately left alone here.)
//
// WHAT IS GENERATED. A sorted list of relative paths. Nothing else.
//
// Not the derived index: `lib/registry.ts` owns the rules that turn paths into
// components — the primary-extension preference that stops `button.rs`
// answering `GET /api/v1/ui/button`, the node-directory parsing, and the
// duplicate-name conflict check. Generating the finished Map would move those
// rules into a build script where the tests do not reach them, and give the
// project a second place for them to be wrong.
//
// Usage:
//   node scripts/generate-registry-index.mjs           write the module
//   node scripts/generate-registry-index.mjs --check   fail if stale (CI)

import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from "node:fs"
import { join } from "node:path"
import prettier from "prettier"

const ROOT = join(process.cwd(), "components", "registry")
const OUT = join(process.cwd(), "lib", "registry.generated.ts")
const check = process.argv.includes("--check")

function fail(msg) {
  console.error(`✗ ${msg}`)
  process.exit(1)
}

if (!existsSync(ROOT)) fail(`no registry tree at ${ROOT}`)

const paths = []
for (const dir of readdirSync(ROOT).sort()) {
  const dirPath = join(ROOT, dir)
  if (!statSync(dirPath).isDirectory()) continue
  for (const file of readdirSync(dirPath).sort()) {
    if (!statSync(join(dirPath, file)).isFile()) continue
    paths.push(`${dir}/${file}`)
  }
}

if (paths.length === 0) fail("registry tree contains no files")

const raw = `/**
 * GENERATED by scripts/generate-registry-index.mjs — do not edit.
 *
 * Every file under \`components/registry/\`, as \`<node-dir>/<filename>\`, sorted.
 * Inlined at build time so \`lib/registry.ts\` needs no directory walk at request
 * time — which is what lets this app run on Cloudflare Workers.
 *
 * Paths only. The rules that turn them into components — extension preference,
 * node parsing, duplicate detection — stay in \`lib/registry.ts\`.
 *
 * Regenerate with \`pnpm registry:index\`; \`pnpm registry:index:check\` is the CI
 * gate.
 */

export const REGISTRY_FILES: readonly string[] = ${JSON.stringify(paths, null, 2)}
`

const config = await prettier.resolveConfig(OUT)
const content = await prettier.format(raw, { ...config, filepath: OUT })

if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : ""
  if (current !== content) {
    fail(
      "lib/registry.generated.ts is stale against components/registry/. " +
        "Run `pnpm registry:index` and commit the result."
    )
  }
  console.log(`✓ generated registry index matches the tree (${paths.length} files)`)
} else {
  writeFileSync(OUT, content)
  console.log(`✓ wrote lib/registry.generated.ts — ${paths.length} files`)
}
