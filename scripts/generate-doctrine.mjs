// Inline `content/doctrine/**/*.mdx` into `lib/doctrine.generated.ts`.
//
// WHY. `lib/doctrine.ts` reads the doctrine tree with `readdirSync` and
// `readFileSync` at request time. That works on Vercel, where the deployment
// has a filesystem, and does not work on Cloudflare Workers, which has none.
// Doctrine is one of three runtime filesystem readers standing between this app
// and Workers (the others being `lib/registry.ts` and `lib/registry-source.ts`).
//
// WHAT IS GENERATED, AND WHAT DELIBERATELY IS NOT. This emits the RAW MDX text,
// keyed by collection and slug — not parsed documents. The frontmatter parser
// stays in `lib/doctrine.ts` and keeps doing the parsing.
//
// That is the whole point. A generator that parsed would be a SECOND parser for
// a format with a hand-written reader, and the two would drift the first time
// the extractor's output changed — which is exactly the class of bug this
// repository keeps paying for. One parser, one behaviour, and the generated file
// carries only bytes it did not interpret.
//
// Usage:
//   node scripts/generate-doctrine.mjs           write the module
//   node scripts/generate-doctrine.mjs --check   fail if stale (CI)

import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from "node:fs"
import { join } from "node:path"
import prettier from "prettier"

const ROOT = join(process.cwd(), "content", "doctrine")
const OUT = join(process.cwd(), "lib", "doctrine.generated.ts")
const check = process.argv.includes("--check")

function fail(msg) {
  console.error(`✗ ${msg}`)
  process.exit(1)
}

if (!existsSync(ROOT)) fail(`no doctrine tree at ${ROOT}`)

const sources = {}
let fileCount = 0

for (const collection of readdirSync(ROOT).sort()) {
  const dir = join(ROOT, collection)
  if (!statSync(dir).isDirectory()) continue

  const docs = {}
  for (const file of readdirSync(dir).sort()) {
    if (!file.endsWith(".mdx")) continue
    docs[file.replace(/\.mdx$/, "")] = readFileSync(join(dir, file), "utf8")
    fileCount++
  }
  // An empty collection directory is not an error — but it is also not worth a
  // key, because `readDoctrineCollection` already answers [] for a missing one.
  if (Object.keys(docs).length > 0) sources[collection] = docs
}

if (fileCount === 0) fail("doctrine tree contains no .mdx files")

const raw = `/**
 * GENERATED by scripts/generate-doctrine.mjs — do not edit.
 *
 * Raw MDX for every document under \`content/doctrine/\`, keyed by collection
 * and slug. Inlined at build time so \`lib/doctrine.ts\` needs no filesystem at
 * request time — which is what lets this app run on Cloudflare Workers.
 *
 * These are UNPARSED bytes on purpose: \`lib/doctrine.ts\` owns the frontmatter
 * parser, and a second one here would drift from it.
 *
 * Regenerate with \`pnpm doctrine:generate\`; \`pnpm doctrine:generate:check\` is
 * the CI gate.
 */

export const DOCTRINE_SOURCES: Readonly<Record<string, Readonly<Record<string, string>>>> =
  ${JSON.stringify(sources, null, 2)}
`

const config = await prettier.resolveConfig(OUT)
const content = await prettier.format(raw, { ...config, filepath: OUT })

if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : ""
  if (current !== content) {
    fail(
      "lib/doctrine.generated.ts is stale against content/doctrine/. " +
        "Run `pnpm doctrine:generate` and commit the result."
    )
  }
  console.log(
    `✓ generated doctrine matches the tree (${fileCount} documents, ${Object.keys(sources).length} collections)`
  )
} else {
  writeFileSync(OUT, content)
  console.log(
    `✓ wrote lib/doctrine.generated.ts — ${fileCount} documents, ${Object.keys(sources).length} collections`
  )
}
