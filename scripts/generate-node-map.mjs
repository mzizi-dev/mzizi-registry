#!/usr/bin/env node
/**
 * Generate the item → node lookup that `mzizi-ui` and `mzizi-plus` use to
 * decide whether a registry item belongs on their subdomain.
 *
 * The node a component belongs to is a fact about where its source lives —
 * `components/registry/n<N>-<label>/` (§8.3) — not a freeform tag a registry
 * entry could drift from. `registry.json`'s `categories` array is written by
 * hand per item and already carries labels that don't line up 1:1 with a node
 * (`components`, `styling-libs`, `agentic-components`), so it is not a safe
 * gating signal. The file path is: every item's `files[].path` starts with
 * `components/registry/nN-*`, and that segment is the actual source of truth
 * the doctrine (`content/doctrine/documentation-architecture-nodes/*.mdx`)
 * describes.
 *
 * Usage:
 *   node scripts/generate-node-map.mjs           write the artifact
 *   node scripts/generate-node-map.mjs --check   fail if it is out of date
 */

import { readFileSync, writeFileSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"
import prettier from "prettier"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
const REGISTRY = join(ROOT, "registry.json")
const OUT = join(ROOT, "lib", "node-map.generated.ts")

const NODE_PATTERN = /^components\/registry\/(n\d+)-/

async function prettified(filePath, source) {
  const config = await prettier.resolveConfig(filePath)
  return prettier.format(source, { ...config, filepath: filePath })
}

const registry = JSON.parse(readFileSync(REGISTRY, "utf8"))

/** @type {Record<string, string>} */
const map = {}
const skipped = []

for (const item of registry.items) {
  const nodes = new Set()
  for (const file of item.files ?? []) {
    const match = NODE_PATTERN.exec(file.path ?? "")
    if (match) nodes.add(match[1])
  }
  if (nodes.size === 0) {
    // Root-level config items (`mzizi-base`, `nyuchi-tokens`) install files
    // outside `components/registry/` and carry no single node — expected, not
    // an error. They are simply absent from the map, and a subdomain proxy
    // that gets asked for one falls through to its "unknown item" behaviour.
    skipped.push(item.name)
    continue
  }
  if (nodes.size > 1) {
    throw new Error(
      `Registry item "${item.name}" installs files under more than one node ` +
        `(${[...nodes].join(", ")}). generate-node-map.mjs assumes one node per ` +
        `item; teach it about split items before adding one.`
    )
  }
  map[item.name] = [...nodes][0]
}

const header = `// GENERATED by scripts/generate-node-map.mjs — do not edit.
//
// Maps a registry item's \`name\` to the node (\`n1\`..\`n11\` today) whose
// directory its source files live under. mzizi-ui and mzizi-plus read this to
// decide whether a requested item belongs on their subdomain — see
// lib/domain-proxy.ts.
//
// Regenerate with \`pnpm node-map:generate\`. CI runs
// \`pnpm node-map:generate:check\`, which fails if this drifts from registry.json.
//
// ${skipped.length} item(s) have no single node and are intentionally absent:
// ${skipped.join(", ")}

/** Item name -> node id (\`"n1"\`..\`"n11"\`). */
export const NODE_MAP: Readonly<Record<string, string>> = `

const output = await prettified(OUT, `${header}${JSON.stringify(map, null, 2)} as const\n`)

if (process.argv.includes("--check")) {
  let current = ""
  try {
    current = readFileSync(OUT, "utf8")
  } catch {
    console.error("✗ lib/node-map.generated.ts is missing. Run `pnpm node-map:generate`.")
    process.exit(1)
  }
  if (current !== output) {
    console.error(
      "✗ lib/node-map.generated.ts is out of date with registry.json. Run `pnpm node-map:generate`."
    )
    process.exit(1)
  }
  console.log(`✓ node map in sync — ${Object.keys(map).length} items`)
} else {
  writeFileSync(OUT, output)
  console.log(`✓ wrote lib/node-map.generated.ts — ${Object.keys(map).length} items`)
}
